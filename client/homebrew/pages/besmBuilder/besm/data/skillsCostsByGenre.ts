// Unavailable skills per genre/subgenre (skills marked '-' in CSV)
export const unavailableSkillsByGenre: Record<string, Record<string, Set<string>>> = Object.fromEntries(
  Object.entries(GeneratedUnavailableByGenre).map(([genre, subMap]) => [
    genre,
    Object.fromEntries(
      Object.entries(subMap as Record<string, string[]>).map(([sub, skills]) => [
        sub,
        new Set<string>(skills),
      ])
    ),
  ])
);

export function isSkillAvailable(
  genre: GenreKey | string | undefined,
  subgenre: string | null | undefined,
  skillName: string
): boolean {
  const g = genre || 'Multi-Genre';
  const sg = subgenre || '';
  const genreMap = unavailableSkillsByGenre[g as string];
  if (!genreMap) return true;
  const set = genreMap[sg];
  if (!set) return true;
  return !set.has(skillName);
}

function resolveCostMap(
  genre: GenreKey | string | undefined,
  subgenre?: string | null
): SkillsCostMap | undefined {
  const activeGenre = genre && skillsCostsByGenre[genre] ? genre : 'Multi-Genre';
  const node = skillsCostsByGenre[activeGenre];
  if (!node) return skillsCostsByGenre['Multi-Genre'] as SkillsCostMap;
  // If node is a nested subgenre map
  if (typeof node === 'object' && node !== null && !('Acrobatics' in node)) {
    const subMap = (node as Record<string, SkillsCostMap>)[subgenre || ''];
    return subMap || (skillsCostsByGenre['Multi-Genre'] as SkillsCostMap);
  }
  return node as SkillsCostMap;
}

export function getSkillRankCost(
  genre: GenreKey | string | undefined,
  skillName: string,
  rank: number,
  subgenre?: string | null
): number {
  const safeRank = Math.min(6, Math.max(1, Math.floor(rank)));
  const idx = safeRank - 1;
  const bySkill = resolveCostMap(genre, subgenre) || {};
  const costs = bySkill[skillName] || (skillsCostsByGenre['Multi-Genre'] as SkillsCostMap)[skillName];
  if (costs && costs[idx] != null) return costs[idx];
  return 1;
}

export function getSkillCostsArray(
  genre: GenreKey | string | undefined,
  skillName: string,
  subgenre?: string | null
): SkillRankCosts {
  const bySkill = resolveCostMap(genre, subgenre) || {};
  return bySkill[skillName] || (skillsCostsByGenre['Multi-Genre'] as SkillsCostMap)[skillName] || [1, 1, 1, 1, 1, 1];
}
